// Builds src/lib/world-dots.ts: a dotted world map for the "ten countries" section.
// Land comes from Natural Earth (public domain) via the world-atlas package. Every dot is a
// zero-length line segment in one SVG path, so ~2,000 dots cost a few kilobytes.
//
//   node scripts/world-dots.mjs
//
// Re-run it after changing the list of countries below; the output is committed.
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topo = require('world-atlas/countries-110m.json');

/** Map units per degree. The drawing spans 180°W–180°E and 75°N–56°S. */
const S = 4;
const TOP = 75;
const BOTTOM = -56;
const STEP = 1.5;
// Only the part of the world the section shows: Africa, Europe, the Gulf and South Asia.
const WEST = -36;
const EAST = 100;
const NORTH = 70;
const SOUTH = -40;
const P = (lng, lat) => [Math.round((lng + 180) * S * 10) / 10, Math.round((TOP - lat) * S * 10) / 10];

// The countries SengetiEdu is set up for (ISO numeric -> two-letter code), each with a pin
// on its capital or main city. Mutare is the head office.
const countries = {
  716: { code: 'ZW', pin: [32.67, -18.97] },
  508: { code: 'MZ', pin: [32.57, -25.97] },
  180: { code: 'CD', pin: [15.27, -4.44] },
  120: { code: 'CM', pin: [11.5, 3.85] },
  404: { code: 'KE', pin: [36.82, -1.29] },
  516: { code: 'NA', pin: [17.07, -22.56] },
  72: { code: 'BW', pin: [25.92, -24.63] },
  784: { code: 'AE', pin: [54.38, 24.45] },
  616: { code: 'PL', pin: [21.01, 52.23] },
  144: { code: 'LK', pin: [79.86, 6.93] },
};

const geo = feature(topo, topo.objects.countries).features;

const polys = geo.map((f) => {
  const g = f.geometry;
  const rings = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  let x0 = 180, y0 = 90, x1 = -180, y1 = -90;
  for (const poly of rings)
    for (const [x, y] of poly[0]) {
      x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y);
    }
  return { id: Number(f.id), rings, box: [x0, y0, x1, y1] };
});

/** Ray casting over a polygon with holes. */
function inPoly(poly, x, y) {
  let inside = false;
  for (const ring of poly)
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];
      // Edges that jump across the date line (Fiji, eastern Russia) would cut the whole row.
      if (Math.abs(xi - xj) > 180) continue;
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
    }
  return inside;
}

const land = [];
const lit = [];
for (let lat = NORTH; lat > SOUTH; lat -= STEP) {
  for (let lng = WEST; lng < EAST; lng += STEP) {
    const hit = polys.find((p) => lng >= p.box[0] && lng <= p.box[2] && lat >= p.box[1] && lat <= p.box[3] && p.rings.some((r) => inPoly(r, lng, lat)));
    if (!hit) continue;
    (countries[hit.id] ? lit : land).push(P(lng, lat));
  }
}

const path = (pts) => pts.map(([x, y]) => `M${Math.round(x)} ${Math.round(y)}h0`).join('');
const pins = Object.values(countries).map((c) => ({ code: c.code, x: P(...c.pin)[0], y: P(...c.pin)[1] }));

const out = `// Generated by scripts/world-dots.mjs from Natural Earth via world-atlas. Do not edit by hand.
export const WORLD_W = ${360 * S};
export const WORLD_H = ${(TOP - BOTTOM) * S};
/** Every land dot outside the highlighted countries. */
export const landDots = '${path(land)}';
/** Dots inside the countries SengetiEdu is set up for. */
export const litDots = '${path(lit)}';
/** One pin per country; the first is the head office. */
export const pins: { code: string; x: number; y: number }[] = ${JSON.stringify(pins)};
`;
fs.writeFileSync(new URL('../src/lib/world-dots.ts', import.meta.url), out);
console.log(`land ${land.length}, lit ${lit.length}, ${(out.length / 1024).toFixed(1)} KB`);
